#!/usr/bin/env node
// Builds NordInvest's English dictionary from crawler dumps.
//   node scripts/i18n-build.mjs <dir with *.json dumps> [extra.json ...]
// Each dump is { "<danish key>": "<english>" } saved from window.__nordinvestI18n
// while browsing the site with ?lang=en. Writes:
//   public/i18n/en.json            everything except blog article bodies
//   public/i18n/blog/<slug>.json   article-body blocks per blog post
//   src/lib/i18n/images.ts         Danish-text images that have an English twin
//   src/lib/i18n/version.ts        cache-busting version
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const [dir, ...extra] = process.argv.slice(2);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const ui = JSON.parse(fs.readFileSync(path.join(root, "public/i18n/en.json"), "utf8") || "{}");
for (const k of Object.keys(ui)) if (k.startsWith("html:")) delete ui[k];
const blogs = {};

for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json"))) {
  const d = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  const blog = f.match(/_blog_([a-z0-9_]+)\.json$/);
  for (const [k, v] of Object.entries(d)) {
    if (typeof v !== "string") continue;
    if (k.startsWith("html:") && blog) {
      const slug = blog[1].replace(/_/g, "-");
      (blogs[slug] ??= {})[k] = v;
    } else if (!k.startsWith("html:")) ui[k] = v;
  }
}
for (const e of extra) for (const [k, v] of Object.entries(JSON.parse(fs.readFileSync(e, "utf8")))) if (!k.startsWith("html:")) ui[k] = v;
// Hand-checked fixes always win.
Object.assign(ui, JSON.parse(fs.readFileSync(path.join(root, "scripts/i18n-overrides.json"), "utf8")));

const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
fs.mkdirSync(path.join(root, "public/i18n/blog"), { recursive: true });
fs.writeFileSync(path.join(root, "public/i18n/en.json"), JSON.stringify(sorted(ui)));
for (const [slug, d] of Object.entries(blogs)) {
  const file = path.join(root, `public/i18n/blog/${slug}.json`);
  const prev = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : {};
  fs.writeFileSync(file, JSON.stringify(sorted({ ...prev, ...d })));
}

// images: foo.webp -> foo-en.webp; a phone crop without its own twin uses the desktop one
const map = {};
const land = path.join(root, "public/landing");
for (const f of fs.readdirSync(land)) {
  if (!/^demo-.*\.webp$/.test(f) || f.endsWith("-en.webp")) continue;
  const base = f.slice(0, -5);
  if (fs.existsSync(path.join(land, `${base}-en.webp`))) map[`/landing/${f}`] = `/landing/${base}-en.webp`;
  else if (base.endsWith("-m") && fs.existsSync(path.join(land, `${base.slice(0, -2)}-en.webp`))) map[`/landing/${f}`] = `/landing/${base.slice(0, -2)}-en.webp`;
}
const blogImg = path.join(root, "public/blog");
for (const d of fs.readdirSync(blogImg)) {
  if (fs.existsSync(path.join(blogImg, d, "figur-en.webp"))) map[`/blog/${d}/figur.webp`] = `/blog/${d}/figur-en.webp`;
}
fs.writeFileSync(
  path.join(root, "src/lib/i18n/images.ts"),
  `// Generated by scripts/i18n-build.mjs. Danish-text images with an English twin.\nexport const EN_IMAGES = new Map<string, string>([\n${Object.entries(map)
    .sort()
    .map(([k, v]) => `  ["${k}", "${v}"],`)
    .join("\n")}\n]);\n`,
);

const version = crypto.createHash("sha1").update(JSON.stringify(ui) + JSON.stringify(blogs) + JSON.stringify(map)).digest("hex").slice(0, 10);
fs.writeFileSync(
  path.join(root, "src/lib/i18n/version.ts"),
  `// Bumped by scripts/i18n-build.mjs whenever the English dictionary changes,\n// so browsers fetch the new file instead of a cached one.\nexport const I18N_VERSION = "${version}";\n`,
);
console.log(`en.json: ${Object.keys(ui).length} keys, blog files: ${Object.keys(blogs).length}, images: ${Object.keys(map).length}, version ${version}`);
